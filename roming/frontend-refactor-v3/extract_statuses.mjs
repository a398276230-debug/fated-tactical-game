// node roming/frontend-refactor-v3/extract_statuses.mjs [--write | --check | --json]
// 离线生成目录。--json 输出原始模板，默认输出目录模块。
import { readFileSync, writeFileSync } from 'node:fs';
import { STATUSES } from '../../src/core/combat.js';
import { statusModifierRange } from '../../src/core/status_modifiers.js';

const target = new URL('../../src/tavern/status-catalog.js', import.meta.url);
// 补充实战结算细节，并集中展示可覆盖数值。
const notes = {
  guard: '仅非反应打击；须未跳过行动、高差≤1且视线通畅。',
  thorns: '不对反应伤害连锁。',
  lock_on: '实际命中加值不限目标；定位动作另记朝向目标。',
  charge: '实际持续期间生效，攻击不消耗。',
  weakness: '读取防守者层数，难度最低0；扫描动作给自身3层。',
  prone: '攻击此单位获得 incomingAccuracy。',
  disarmed: '仅贴状态不会卸武器；缴械动作另清主手和weapon，到期不自动归还。',
};
const descriptions = {
  bleed: '回合末每层结算一次伤害。', poison: '回合初每层结算一次伤害。',
  guarded: '受到的伤害降低。', vulnerable: '受到的伤害增加。', sunder: '护甲降低。',
  mark: '攻击此单位的命中提高。', haste: '移动距离增加。', weakness: '每层降低意图难度。',
};
const statuses = Object.values(STATUSES);
const rows = statuses.map(s => {
  if (s.durationType !== 'battle_turns') throw Error(`Update duration legend for ${s.id}`);
  const params = Object.entries(s.modifiers).map(([k, v]) => `${k}=${v}（${statusModifierRange(k, s)}）`).join('，');
  return [s.id, `${s.icon}${s.name}`, s.category, s.remainingTurns,
    `${descriptions[s.id] ?? s.description}${notes[s.id] ?? ''} 默认 ${params}`, `${s.stackRule}/${s.maxStacks}`].join(' | ');
});
const catalog = [
  '状态 ID：内置仅以下各行；其他 ID 必须先在 statusTemplates 注册并通过校验，不可覆盖内置。',
  'ID | 图标中文名 | 类别 | 默认持续（battle_turns，自身回合数） | 默认数值（可被技能/装备/API 覆盖，括号内为合法范围） | 重复施加规则/模板层数上限',
  '以下数值均为模板默认值。技能、装备与 API 可在施加时覆盖（见 modifiers 参数），不影响模板本身。设计技能时应按技能自己的强度设定数值。',
  ...rows,
  `默认 tickTiming：onTurnStart；例外：${statuses.filter(s => s.tickTiming !== 'onTurnStart').map(s => `${s.id}=${s.tickTiming}`).join('、')}。施加当回合不跳伤/治疗、不扣时长。`,
  'grantStatus：refresh 重设时长，replace 替换不累加（护盾重设池）；stack 累加至上限，未指定时长时取旧剩余与模板默认的较大值，指定则重设。',
  '校验≠默认：remainingTurns 整数1–100；durationType 可为 battle_turns（自身回合末递减）、until_removed 或 persistent（后两者不递减，persistent 不受 cleanse）。',
  '实例 stacks、maxStacks 均为整数，1≤stacks≤maxStacks≤模板上限；技能 status 效果 turns 1–100、stacks 1–10，内置施加时仍截至实例上限，自定义不可超模板上限（自定义模板 maxStacks 1–10）。',
  '实例展示字段与模板一致，modifiers 键集与模板一致，值可在合法范围内变化。仅 shield 实例有 amount（剩余护盾池）；施加或 patchStatus 覆盖 modifiers.amount 会设置护盾池，施加时旧式 amount 参数优先。',
].join('\n');
const moduleText = '// Generated by roming/frontend-refactor-v3/extract_statuses.mjs --write.\nexport const STATUS_CATALOG = `' + catalog.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${') + '`;\n';
switch (process.argv[2]) {
  case undefined: process.stdout.write(moduleText); break;
  case '--write': writeFileSync(target, moduleText); break;
  case '--check':
    if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== moduleText) throw Error('Stale status-catalog.js; regenerate with --write');
    console.log(`${rows.length} statuses; ${catalog.length} UTF-16 code units`);
    break;
  case '--json': console.log(JSON.stringify(STATUSES, null, 2)); break;
  default: throw Error('Expected --write, --check, --json, or no option');
}
